    ps = p['ps_id']; ins = [x for x in I if x['ps_id'] == ps]
    svc = collections.OrderedDict(); xs = ''
    for x in ins:
        for ln in x['opportunity'].split('\n'):
            if ln.startswith('แผนดูแลที่เปิดขายได้'): svc[ln.split(':', 1)[1].strip()] = 1
            if ln.startswith('คนไข้กลุ่มเดียวกันมักมีเรื่อง') and not xs: xs = ln.split('มักมีเรื่อง', 1)[1].split(' ร่วมด้วย')[0].strip()
