def keywords(pains, n=6):
    lists = [[t.strip() for t in C[p]['customer_search_terms'].split('|')][2:] for p in pains if p in C]
    out = []
    for i in range(max(map(len, lists)) if lists else 0):
        for l in lists:
            if i < len(l) and l[i] and l[i] not in out: out.append(l[i])
    return out[:n]

