def clean_limits(t):
    n=''
    t=re.sub(r'\[PX-\d+\]\s*','',t or '').replace('\n',' · ')
    m=re.search(r'จำนวน:\s*([^·]+?)\s*·\s*',t)
    if m: n=m.group(1).strip(); t=t[:m.start()]+t[m.end():]
    parts=[p.strip() for p in re.split(r'[;·]',t) if p.strip()]
    drop=('รหัสแทน','ข้อมูลเติมของรายการเดิม','เข้ารหัส','ตามข้อกำหนดนำเข้า','ตามโจทย์','ห้าม')
    parts=[p for p in parts if not any(k in p for k in drop)]
    return n,' · '.join(parts)
