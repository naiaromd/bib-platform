	`id` text PRIMARY KEY NOT NULL,
	`account_id` text NOT NULL,
	`report_month` text NOT NULL,
	`reported_paid_sessions` integer DEFAULT 0 NOT NULL,
	`eligible_paid_sessions` integer DEFAULT 0 NOT NULL,
	`complimentary_sessions` integer DEFAULT 0 NOT NULL,
	`training_sessions` integer DEFAULT 0 NOT NULL,
	`reported_gross_revenue` integer DEFAULT 0 NOT NULL,
	`eligible_gross_revenue` integer DEFAULT 0 NOT NULL,
	`bib_share_rate_bps` integer DEFAULT 4000 NOT NULL,
	`bib_share_vat_inclusive` integer DEFAULT 0 NOT NULL,
	`linna_share` integer DEFAULT 0 NOT NULL,
	`deductible_marketing` integer DEFAULT 0 NOT NULL,
	`approved_refunds` integer DEFAULT 0 NOT NULL,
	`total_usage_minutes` integer DEFAULT 0 NOT NULL,
	`exception_count` integer DEFAULT 0 NOT NULL,
	`status` text DEFAULT 'Needs Review' NOT NULL,
	`source_note` text DEFAULT '' NOT NULL,
	`updated_at` text DEFAULT CURRENT_TIMESTAMP NOT NULL
);
